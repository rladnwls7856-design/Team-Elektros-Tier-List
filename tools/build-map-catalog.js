#!/usr/bin/env node
/*
 * Regenerates js/maps-catalog.js from the "Brawlstars map" folder.
 * A static GitHub Pages site cannot list a directory, so the map list ships as a script.
 * Usage: npm run catalog   (run again whenever map images are added, renamed or removed)
 */
"use strict";
const fs = require("node:fs");
const path = require("node:path");
const { buildCatalog, catalogStats } = require("../js/catalog.js");

const ROOT_DIR = "Brawlstars map";
const PROJECT = path.join(__dirname, "..");
const OUT = path.join(PROJECT, "js", "maps-catalog.js");

// Width/height live in the PNG IHDR chunk at bytes 16-23; reading 24 bytes avoids decoding
// 56MB of images. They let the page reserve the right aspect ratio before an image loads.
function pngSize(file) {
  const fd = fs.openSync(file, "r");
  try {
    const head = Buffer.alloc(24);
    fs.readSync(fd, head, 0, 24, 0);
    if (head.readUInt32BE(0) !== 0x89504e47 || head.toString("ascii", 12, 16) !== "IHDR") return { w: 0, h: 0 };
    return { w: head.readUInt32BE(16), h: head.readUInt32BE(20) };
  } finally {
    fs.closeSync(fd);
  }
}

function scanFolder(rootPath) {
  const entries = [];
  for (const mode of fs.readdirSync(rootPath, { withFileTypes: true })) {
    if (!mode.isDirectory()) continue;
    for (const file of fs.readdirSync(path.join(rootPath, mode.name), { withFileTypes: true })) {
      if (!file.isFile() || !/\.png$/i.test(file.name)) continue;
      entries.push({ mode: mode.name, file: file.name, ...pngSize(path.join(rootPath, mode.name, file.name)) });
    }
  }
  return entries;
}

function render(catalog) {
  return (
    "/* Generated by tools/build-map-catalog.js — do not edit by hand. Run `npm run catalog` after changing \"" +
    ROOT_DIR +
    "\". */\n" +
    "(function (root, data) {\n" +
    '  if (typeof module === "object" && module.exports) module.exports = data;\n' +
    "  else root.BRAWL_MAP_CATALOG = data;\n" +
    '})(typeof globalThis !== "undefined" ? globalThis : this, ' +
    JSON.stringify(catalog) +
    ");\n"
  );
}

if (require.main === module) {
  const catalog = buildCatalog(ROOT_DIR, scanFolder(path.join(PROJECT, ROOT_DIR)));
  fs.writeFileSync(OUT, render(catalog));
  const s = catalogStats(catalog);
  console.log(`js/maps-catalog.js: ${s.modes} modes, ${s.maps} maps, ${s.images} images`);
}

module.exports = { scanFolder, pngSize, render };
